import { Injectable } from '@nestjs/common';

/** DI-токен для реализации распознавания речи — потребители зависят от интерфейса, не от класса. */
export const STT_SERVICE = Symbol('STT_SERVICE');

// `SttEngine` / `DEFAULT_STT_ENGINE` / `resolveSttEngine` — в `stt-engine.ts` (модуль без зависимостей).

export interface SttInput {
  originalName: string;
  size: number;
  /** Ключ бинарника в `FileStorageService` — движок берёт файл с диска по нему. */
  storageKey: string;
  /** mime исходного файла — решает, нужна ли конвертация в WAV (Фаза 2). */
  mimeType: string;
  /** Прерывание транскрибации (таймаут / остановка приложения — Фаза 3). */
  signal?: AbortSignal;
}

export interface SttService {
  transcribe(input: SttInput): Promise<string>;
}

/**
 * Единственная реализация STT в этой итерации (реальный движок — вне скоупа PRD).
 * Детерминированная: транскрипт выводится из метаданных файла, без чтения содержимого и
 * без ветвления по `NODE_ENV` (локальный pre-commit идёт с `NODE_ENV=development`, CI — с `test`).
 * Путь ошибки STT в e2e проверяется через `.overrideProvider(STT_SERVICE)` — в проде тестовых веток нет.
 */
@Injectable()
export class StubSttService implements SttService {
  transcribe(input: SttInput): Promise<string> {
    // Извлечь имя файла без расширения для использования в контексте встречи
    const baseName = input.originalName.replace(/\.[^.]+$/, '');
    // Экранировать кавычки и обратные слеши для безопасной подстановки
    const topic = (baseName.length > 50 ? 'проект' : baseName)
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"');

    // Генерировать реалистичный транскрипт для тестирования суммаризации
    const transcript = `[00:00] Александр: Добрый день, коллеги! Начинаем встречу по теме "${topic}".
[00:15] Мария: Привет всем! Давайте обсудим текущие задачи и приоритеты на эту неделю.
[00:30] Иван: Согласен. Первый вопрос — завершение модуля авторизации. У нас есть прогресс?
[00:45] Мария: Да, по авторизации хорошие новости. Основная функциональность реализована и протестирована.
[01:00] Александр: Отлично! Какие следующие шаги нам нужно предпринять?
[01:15] Иван: Нужно провести code review и написать дополнительные unit-тесты для edge cases.
[01:30] Мария: Я могу взять на себя code review. Когда планируем закончить?
[01:45] Александр: Давайте целимся на конец этой недели. Иван, ты можешь заняться тестами?
[02:00] Иван: Да, без проблем. Возьму тесты на себя, постараюсь закончить к пятнице.
[02:15] Мария: Хорошо. Есть еще какие-то блокеры или вопросы по задаче?
[02:30] Иван: Нет, все понятно. Можем двигаться дальше.
[02:45] Александр: Отлично. Решили: Мария делает code review, Иван пишет тесты, дедлайн — пятница.
[03:00] Мария: Договорились. Что насчет следующей задачи?
[03:15] Александр: Следующая — интеграция с API платежной системы. Это приоритет номер два.
[03:30] Иван: Я могу взять эту задачу на следующую неделю, после того как закончу с тестами.
[03:45] Мария: Звучит разумно. Давайте так и сделаем.
[04:00] Александр: Отлично, записали. Встречу можно завершать. Всем продуктивной недели!
[04:15] Мария: Спасибо, до связи!
[04:30] Иван: До встречи на следующей неделе!`;

    return Promise.resolve(transcript);
  }
}
